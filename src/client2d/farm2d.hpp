#pragma once
// AL-112: fields and kitchen gardens on the 2D map. A crop object of the sim
// (objects.json `crop`: field, garden) is one point with its state in stock
// (strips, tilled, sown, grown, ripe, ripe_age, farming.cpp). Here it gets
// ground: the field its zone of the village plan cut into bands, one per
// strip; the garden beds round its spot. Each band / bed gets the stage the
// stock says (fallow, tilled, sown .. heading, ripe, over, stubble) and a
// 16x16 tile for it; the kitchen garden's beds also a crop (the sim grows one
// "vegetables": cabbage, carrots... are the view's, stable per garden, bed
// pair and year). Read-only over the sim.
//
// Layout and tiles are data: content/sprites_2d/crops2d.json "plots"
// (generated by tools/content_gen/gen_crops_2d.py).

#include <map>
#include <string>
#include <utility>
#include <vector>

#include "client2d/grid2d.hpp"

namespace lr::client2d {

struct PlotRule {
    std::string layout = "strips";   // strips | beds
    double stripM = 1.2, halfW = 8.0;   // strips: band depth, half width when there is no zone
    int bedLen = 3, maxRows = 6, pickPairs = 2;   // beds
    std::vector<std::pair<std::string, double>> stages;   // growing stages by grown / grow_days (upper bounds)
    std::map<std::string, std::vector<std::string>> tiles; // stage -> sprites (by cell variant)
    std::vector<std::string> path;                        // beds: the path between columns
    // beds: crop -> stage -> sprites (stages young, grown, ripe; others from `tiles`)
    std::map<std::string, std::map<std::string, std::vector<std::string>>> crops;
};

struct CropRules {
    std::map<std::string, PlotRule> byType;   // crop object type -> rule
    static CropRules fromJson(const Json& plots);   // "plots" of crops2d.json
    bool empty() const { return byType.empty(); }
};

// One band / bed of a plot as the view shows it.
struct PlotPart {
    std::string stage;   // fallow | stubble | tilled | sown | sprout | young | grown | heading | ripe | over
    std::string crop;    // beds: the crop of the bed
};

// The stage of every strip of one crop object, in band / bed order.
std::vector<PlotPart> plotParts(const sim::World& w, const sim::WorldObject& o, const PlotRule& rule);

// Paints the plots that reach into the window: Grid2d::crop / cropTiles / plots.
void paintCrops(const sim::World& w, const CropRules& rules, Grid2d& g);

} // namespace lr::client2d
