# LR-161: the icons the 2D client lacked: things, objects and acts as 16x16 grids of
# sprites.json palette letters ('.' clear), in the style of the AL-95 sprites (a 'k' outline,
# the lit side light, the far side dark). gen_sprites_2d.py merges ICONS into sprites.json;
# gen_icons_2d.py maps the sim's ids onto them (items, objects, acts).
# Palette: k outline, w linen, W/m/M stone and metal, n/N wood, e/E leather, t/T straw,
# y/o gold and crust, r/R red, G/D/l green, u/U water, v/V violet, z/Z clay, f/F fire, x soot.


def P(*rows):
    out = []
    for r in rows:
        assert len(r) <= 16, (len(r), r)
        out.append((r + '.' * 16)[:16])
    assert len(out) <= 16, len(out)
    while len(out) < 16:
        out.append('.' * 16)
    return out


