// LR-170: exports the approved bestiary sheet (bestiary_sheet.html, the same page as the
// artifact) into content/sprites_2d/beasts2d.json: per beast its own palette and rows of letters.
// Run: node tools/content_gen/beasts2d/gen_beasts_2d.js   (needs playwright with chromium)
const path = require('path'), fs = require('fs');
const { chromium } = require('playwright');
const ROOT = path.resolve(__dirname, '../../..');
const OUT = path.join(ROOT, 'content/sprites_2d/beasts2d.json');
// letters for the palette: printable ASCII without '.', '"', '\\'
const LETTERS = [...Array(94)].map((_, i) => String.fromCharCode(33 + i)).filter(c => c !== '.' && c !== '"' && c !== '\\');
(async () => {
  const b = await chromium.launch();
  const p = await b.newPage();
  await p.goto('file://' + path.join(__dirname, 'bestiary_sheet.html'));
  await p.waitForTimeout(300);
  const raw = await p.evaluate(() => {
    const out = {};
    for (const belt of BELTS) for (const [id] of belt.list) {
      const c = B[id]();
      const d = c.getContext('2d').getImageData(0, 0, c.width, c.height).data;
      out[id] = { w: c.width, h: c.height, px: Array.from(d) };
    }
    return out;
  });
  await b.close();
  const hex = (r, g, bb, a) => '#' + [r, g, bb].map(v => v.toString(16).padStart(2, '0')).join('') + (a < 255 ? a.toString(16).padStart(2, '0') : '');
  const beasts = {};
  for (const [id, s] of Object.entries(raw)) {
    // crop to the painted box, keep the feet on the last row
    let x0 = s.w, y0 = s.h, x1 = -1, y1 = -1;
    for (let y = 0; y < s.h; y++) for (let x = 0; x < s.w; x++) if (s.px[(y * s.w + x) * 4 + 3] > 0) {
      x0 = Math.min(x0, x); y0 = Math.min(y0, y); x1 = Math.max(x1, x); y1 = Math.max(y1, y);
    }
    const pal = {}, idx = new Map(), rows = [];
    for (let y = y0; y <= y1; y++) {
      let row = '';
      for (let x = x0; x <= x1; x++) {
        const i = (y * s.w + x) * 4, a = s.px[i + 3];
        if (!a) { row += '.'; continue; }
        const h = hex(s.px[i], s.px[i + 1], s.px[i + 2], a);
        if (!idx.has(h)) {
          if (idx.size >= LETTERS.length) throw new Error(id + ': more than ' + LETTERS.length + ' colours');
          idx.set(h, LETTERS[idx.size]); pal[LETTERS[idx.size - 1]] = h;
        }
        row += idx.get(h);
      }
      rows.push(row);
    }
    beasts[id] = { pal, rows };
  }
  const doc = 'LR-170: beasts and undead of the belts in the approved 48x64 style. Per beast: pal (letter -> #rrggbb[aa]) and rows (top to bottom, "." = empty), side view facing east, mirrored for the west, feet on the last row. Drawn at figures2d.json world_px_per_art_px, like the people. Species without an entry keep the old blob. Generated by tools/content_gen/beasts2d/gen_beasts_2d.js from bestiary_sheet.html; editable by hand (the window reloads it on start).';
  // one beast per line block: rows one per line, readable diffs
  let s = '{\n "_doc": ' + JSON.stringify(doc) + ',\n "beasts": {\n';
  s += Object.entries(beasts).map(([id, v]) => '  ' + JSON.stringify(id) + ': {\n   "pal": ' + JSON.stringify(v.pal) + ',\n   "rows": [\n' + v.rows.map(r => '    ' + JSON.stringify(r)).join(',\n') + '\n   ]\n  }').join(',\n');
  s += '\n }\n}\n';
  fs.writeFileSync(OUT, s);
  console.log('beasts', Object.keys(beasts).length, Object.entries(beasts).map(([k, v]) => k + ':' + v.rows[0].length + 'x' + v.rows.length + '/' + Object.keys(v.pal).length).join(' '));
})();
